"""Host binding contracts. All completion methods must be synchronous."""

from typing import Protocol

from ..algorithm.packing import Packing
from .state import Layout, Request


class CacheBackend(Protocol):
    block_size: int

    def choose(self, layout: Layout, keep: int, recorded=None): ...
    def move(self, packing: Packing): ...
    def synchronize(self) -> None: ...


class WorkerPort(Protocol):
    def quiesce(self, instance: str) -> None: ...
    def install(
        self, request: Request, version: int, layouts: dict[int, Layout]
    ) -> None: ...
    def commit(self, instance: str, version: int) -> None: ...
    def forget(self, instance: str) -> None: ...


class ReplayPort(Protocol):
    def prefill(self, request: Request, tokens: tuple[int, ...]) -> None: ...
    def decode_known(self, request: Request, token: int) -> None:
        """Forward a known token without sampling, RNG advance or output delivery."""
        ...


class AllocatorPort(Protocol):
    def allocate(self, owner: tuple[str, int], count: int): ...
    def validate(self, owner: tuple[str, int], pages) -> None: ...
    def release_once(self, owner: tuple[str, int], pages, transaction: str) -> None: ...
    def release_request(self, instance: str) -> None: ...
    def forget_releases(self, instance: str) -> None: ...


class StepPort(Protocol):
    def before_decode(self, request: Request):
        """Called after outputs and device reads complete, before allocation."""
        ...


class LifecyclePort(Protocol):
    def retire(self, request: Request, phase: str = "finished") -> None:
        """Stop forwards, synchronize, detach worker references, then release pages."""
        ...
